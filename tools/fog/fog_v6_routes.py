def _norm(dx, dy):
    n = (dx * dx + dy * dy) ** 0.5
    if n < 1e-6:
        return (0.0, 0.0)
    return (dx / n, dy / n)


def pre_of(berth, stand, k=5.5):
    """站位 stand 的“再远一点”的点，保证 stand-pre 的方向指向泊位。"""
    bx, by = PRECISE[berth]
    ux, uy = _norm(stand[0] - bx, stand[1] - by)
    return (stand[0] + k * ux, stand[1] + k * uy)


def inside_rect(berth, xy, pad=0.0):
    x0, x1, y0, y1 = RECT[berth]
    return (x0 - pad) <= xy[0] <= (x1 + pad) and (y0 - pad) <= xy[1] <= (y1 + pad)


def self_check():
    """离线自检：站位朝向、pre 是否落在泊位内、B 段是否在车道附近。"""
    bad = []
    for berth, roles in STAND.items():
        bx, by = PRECISE[berth]
        for role, (vid, stand, pre) in roles.items():
            hx, hy = _norm(stand[0] - pre[0], stand[1] - pre[1])       # 到达时的车头方向
            tx, ty = _norm(bx - stand[0], by - stand[1])               # 指向泊位
            dot = hx * tx + hy * ty
            if dot < 0.985:                                            # ~10° 以内
                bad.append("%s/%s 朝向偏 (cos=%.3f)" % (berth, role, dot))
            if inside_rect(berth, pre):
                bad.append("%s/%s 的 pre %s 落在泊位矩形内" % (berth, role, pre))
            if inside_rect(berth, stand) and role == "obs":
                bad.append("%s 观测站位 %s 落在泊位矩形内" % (berth, stand))
    return bad


